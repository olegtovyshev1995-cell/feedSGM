"""Сборка промпта из скилла car-spec-researcher для запуска через Claude API.

Скилл — это многофайловый промпт (SKILL.md + references). Здесь он
собирается в системный промпт с двумя добавками:
  1. Режим API: не сохранять файлы и не запускать скрипты — вернуть всё в ответе.
  2. Контракт вывода: в конце ответа — JSON-блок с ПРЯМЫМИ ссылками на
     подтверждённые фото, чтобы пайплайн надёжно их извлёк (для imgbb).
"""

from __future__ import annotations

from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent / "skills" / "car-spec-researcher"

# Для стадии «спека + фото» подключаем только релевантные references.
# ad-script.md и company-profile.md относятся к Этапу 2 (текст объявления)
# и здесь не нужны — экономим токены промпта.
_REFERENCES = [
    "spec-template.md",
    "photo-matching.md",
    "sources-and-checks.md",
    "known-traps.md",
    "market-versions.md",
]

# Метка-разделитель JSON-блока с фото (для устойчивого парсинга).
PHOTOS_JSON_TAG = "PHOTOS_JSON"

_API_MODE = """
## Режим запуска: API (нет файловой системы и запуска скриптов)

Ты работаешь через API, а не в Claude с файлами. Поэтому:
- НЕ сохраняй файлы и не ссылайся на /mnt/... — верни результат прямо в ответе.
- НЕ запускай convert.py / check_ad.py — конвертируй единицы сам и показывай
  формулу в строке (как того требует шаблон).
- Всё остальное из инструкции скилла соблюдай строго: только найденные в этой
  сессии источники, метки [Факт]/[Расчёт]/[Уточнить], фото = спецификация.
"""

_OUTPUT_CONTRACT = f"""
## Формат ответа (строго)

1. Сначала — файл спецификации в Markdown по `spec-template.md` (блоки 1–14,
   включая блок 14 «Фотографии» с реестром P-n).
2. В САМОМ КОНЦЕ ответа — ровно один блок ```json``` с меткой {PHOTOS_JSON_TAG}
   со списком подтверждённых фотографий:

```json {PHOTOS_JSON_TAG}
{{"photos": [
  {{"image_url": "<ПРЯМАЯ ссылка на файл изображения>",
    "source_url": "<страница-источник с подписью>",
    "angle": "<ракурс/что изображено>",
    "proof": "<чем доказано соответствие модификации>",
    "color": "<цвет на фото>",
    "status": "фото-факт|фото-уточнить"}}
]}}
```

Жёсткие правила для JSON:
- Включай ТОЛЬКО фото с доказанным соответствием версии (как в блоке 14).
  Никаких «похожих» и неподтверждённых.
- `image_url` — ПРЯМАЯ ссылка на сам файл изображения (обычно оканчивается на
  .jpg/.jpeg/.png/.webp либо отдаёт именно картинку). Если удалось найти только
  страницу-источник без прямой ссылки на файл — такое фото в JSON НЕ включай.
- Если подтверждённых фото с прямой ссылкой нет — верни {{"photos": []}}.
- JSON должен быть валидным (двойные кавычки, без комментариев).
"""


def load_skill_text() -> str:
    """Собирает текст скилла: SKILL.md + подключённые references."""
    parts: list[str] = []
    skill_md = SKILL_DIR / "SKILL.md"
    parts.append(skill_md.read_text(encoding="utf-8"))
    for ref in _REFERENCES:
        path = SKILL_DIR / "references" / ref
        parts.append(f"\n\n===== references/{ref} =====\n\n" + path.read_text(encoding="utf-8"))
    return "\n".join(parts)


def build_system_prompt() -> str:
    """Системный промпт = скилл + режим API + контракт вывода (стабилен → кэш)."""
    return load_skill_text() + "\n\n" + _API_MODE + "\n" + _OUTPUT_CONTRACT


def build_user_prompt(make: str, model: str, modification: str, year: str, vin: str) -> str:
    """Пользовательский промпт: конкретная модификация под карточки классифайдов."""
    lines = [
        "Собери спецификацию и подбери фото под эту модификацию "
        "(для карточек Авито/Auto.ru/Drom):",
        f"- Марка: {make}",
        f"- Модель: {model}",
        f"- Модификация: {modification or '(не указана — определи по остальным данным)'}",
        f"- Год: {year or '(не указан)'}",
        f"- VIN: {vin}",
        "",
        "Нужны: файл спецификации по шаблону и JSON-блок с подтверждёнными фото "
        "в конце (по контракту вывода выше).",
    ]
    return "\n".join(lines)
